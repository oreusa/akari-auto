def rank_short(nm):
    """ランキングの商品名は宣伝の言葉が多い。【】・＼／・★★・クーポンなどを外して、先頭の言葉を30字まで。"""
    t = re.sub(r"[【\[［(（＼<〈《][^】\]］)）／>〉》]*$", " ", nm)  # 45字で切れて閉じていないかっこ
    t = PROMO.sub(" ", t)
    t = re.sub(r"[!！?？|｜♪◆■●◎※→～〜]+", " ", t)
    ws = [w for w in t.split() if not re.fullmatch(r"[\d,.%％円本個袋枚kgKGmlL]+", w)]
    s = ""
    for w in ws:
        if len(s) + len(w) + 1 > 30: break
        s = (s + " " + w).strip()
    return s  # 宣伝の言葉しか無い名前は空（その商品は使わない）


